import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const destination = join(root, 'skills/cc/scripts/vendor');
await mkdir(destination, { recursive: true });
await build({
  stdin: { contents: 'export { parse as parseToml } from "smol-toml"; export { parse as parseYaml } from "yaml"; export { default as makeMatcher } from "picomatch";', resolveDir: root },
  bundle: true, platform: 'node', format: 'esm', target: 'node22',
  outfile: join(destination, 'parsers.mjs'),
  banner: { js: '// Generated by installer/build-parsers.mjs. See LICENSE.parsers.txt for notices.\nimport { createRequire } from "node:module"; const require = createRequire(import.meta.url);' },
});
let notices = 'Bundled data parsers. Rebuild with npm run build:parsers.\n';
for (const name of ['smol-toml', 'yaml', 'picomatch']) {
  const directory = join(root, 'node_modules', name);
  const metadata = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  notices += `\n${name} ${metadata.version}\n\n${await readFile(join(directory, 'LICENSE'), 'utf8')}\n`;
}
await writeFile(join(destination, 'LICENSE.parsers.txt'), notices.trimEnd() + '\n');
